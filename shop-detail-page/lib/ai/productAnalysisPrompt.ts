export function buildProductAnalysisPrompt(sourceText: string | null, imageCount: number): string {
  const imageNote =
    imageCount > 1
      ? `상품 이미지 ${imageCount}장(대표이미지 1장 + 참고이미지 ${imageCount - 1}장)이 함께 제공된다. 모든 이미지를 종합해서 분석하라.`
      : `상품 이미지가 제공된다.`;

  if (sourceText && sourceText.trim()) {
    return `${imageNote} 이미지와 아래 상품 원본 정보를 함께 분석하여 아래 예시처럼 깊고 구체적으로 빠짐없이 정리하라. JSON만 출력하고 다른 설명은 출력하지 마라.

# 원본 정보
${sourceText.trim()}

# 예시
${FEW_SHOT_EXAMPLE}`;
  }

  return `${imageNote} 분석하여 아래 예시처럼 정리하라. JSON만 출력하고 다른 설명은 출력하지 마라.

# 예시
${FEW_SHOT_EXAMPLE}`;
}

export interface RawProductAnalysis {
  상품명?: string;
  카테고리?: string;
  상품가격?: string;
  할인가격?: string;
  핵심특징?: string[];
  상세스펙?: Record<string, string>;
  사용방법?: string[];
  타겟고객?: string[];
  디자인정보?: {
    메인컬러?: string;
    서브컬러?: string;
    배경스타일?: string;
    분위기키워드?: string | string[];
    폰트스타일?: string;
    레이아웃밀도?: string;
  };
}
