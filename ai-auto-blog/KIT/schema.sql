-- 공통: updated_at 자동 갱신
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------
-- 1. 회원 본인 API 키(OpenAI·Claude·Gemini·Perplexity·YouTube) — 본인 것만 저장·조회
-- ---------------------------------------------------------------------
create table if not exists public.user_api_keys (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  provider text not null,
  api_key text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_api_keys_user_provider_unique unique (user_id, provider),
  constraint user_api_keys_provider_check check (provider = any (array['openai','anthropic','gemini','perplexity','youtube_api_key']::text[]))
);
alter table public.user_api_keys enable row level security;
drop policy if exists user_api_keys_select_own on public.user_api_keys;
create policy user_api_keys_select_own on public.user_api_keys for select to authenticated using (auth.uid() = user_id);
drop policy if exists user_api_keys_insert_own on public.user_api_keys;
create policy user_api_keys_insert_own on public.user_api_keys for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists user_api_keys_update_own on public.user_api_keys;
create policy user_api_keys_update_own on public.user_api_keys for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists user_api_keys_delete_own on public.user_api_keys;
create policy user_api_keys_delete_own on public.user_api_keys for delete to authenticated using (auth.uid() = user_id);
drop trigger if exists user_api_keys_set_updated_at on public.user_api_keys;
create trigger user_api_keys_set_updated_at before update on public.user_api_keys for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 2. 블로그 작성자(회원마다 한 줄, 글을 처음 만들 때 자동 생성)
-- ---------------------------------------------------------------------
create table if not exists public.blog_authors (
  id bigint generated by default as identity primary key,
  name text not null,
  role text default '에디터',
  avatar_url text,
  created_at timestamptz default now(),
  user_id uuid references auth.users(id) on delete cascade
);
create index if not exists blog_authors_user_id_idx on public.blog_authors(user_id);

-- ---------------------------------------------------------------------
-- 3. 내 카테고리(회원 본인 소유)
-- ---------------------------------------------------------------------
create table if not exists public.blog_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  created_at timestamptz default now(),
  sort_order bigint not null default 0,
  user_id uuid not null references auth.users(id) on delete cascade
);
create unique index if not exists blog_categories_user_slug_key on public.blog_categories(user_id, slug);

-- ---------------------------------------------------------------------
-- 4. 블로그 글(본문은 HTML, 이미지는 아래 post-images 버킷 주소)
--    naver_* · extension_* 칸은 원본 프로그램의 자동 포스팅용이라 이 배포판에서는 비어 있습니다(코드 호환용으로 둠).
-- ---------------------------------------------------------------------
create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  excerpt text,
  content text not null,
  reading_minutes integer default 5,
  published_at timestamptz default now(),
  author_id bigint references public.blog_authors(id) on delete set null,
  created_at timestamptz default now(),
  like_count integer not null default 0,
  user_id uuid references auth.users(id) on delete cascade,
  extension_handoff_at timestamptz,
  naver_input_status text,
  naver_input_completed_at timestamptz,
  naver_input_error text,
  naver_run_id uuid,
  naver_lease_expires_at timestamptz,
  naver_category jsonb
);
create index if not exists blog_posts_user_id_idx on public.blog_posts(user_id, published_at desc);

create table if not exists public.blog_post_categories (
  post_id bigint not null references public.blog_posts(id) on delete cascade,
  category_id bigint not null references public.blog_categories(id) on delete cascade,
  primary key (post_id, category_id)
);

-- ---------------------------------------------------------------------
-- 5. 수집한 글감(주제 후보)
-- ---------------------------------------------------------------------
create table if not exists public.blog_candidates (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  source_type text not null,
  source_input text not null,
  title text not null,
  summary text not null default '',
  keywords text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  category_id bigint references public.blog_categories(id) on delete set null
);
create index if not exists blog_candidates_user_idx on public.blog_candidates(user_id, created_at desc);
drop trigger if exists blog_candidates_set_updated_at on public.blog_candidates;
create trigger blog_candidates_set_updated_at before update on public.blog_candidates for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 7. 보안 정책 — 본인 데이터만(원본 프로그램과 같은 규칙)
-- ---------------------------------------------------------------------
alter table public.blog_posts enable row level security;
alter table public.blog_authors enable row level security;
alter table public.blog_candidates enable row level security;
alter table public.blog_categories enable row level security;
alter table public.blog_post_categories enable row level security;

revoke all on public.blog_posts, public.blog_authors, public.blog_candidates, public.blog_categories, public.blog_post_categories from anon, public;
grant select, insert, update, delete on public.blog_posts, public.blog_authors, public.blog_candidates, public.blog_categories, public.blog_post_categories to authenticated;

drop policy if exists blog_posts_owner on public.blog_posts;
create policy blog_posts_owner on public.blog_posts for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists blog_authors_owner on public.blog_authors;
create policy blog_authors_owner on public.blog_authors for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists blog_candidates_owner on public.blog_candidates;
create policy blog_candidates_owner on public.blog_candidates for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists blog_categories_owner on public.blog_categories;
create policy blog_categories_owner on public.blog_categories for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists blog_post_categories_owner on public.blog_post_categories;
create policy blog_post_categories_owner on public.blog_post_categories for all to authenticated
  using (exists (select 1 from public.blog_posts p where p.id = post_id and p.user_id = auth.uid()))
  with check (
    exists (select 1 from public.blog_posts p where p.id = post_id and p.user_id = auth.uid())
    and exists (select 1 from public.blog_categories c where c.id = category_id and c.user_id = auth.uid())
  );

-- ---------------------------------------------------------------------
-- 8. 이미지 저장소(post-images, 공개 주소) — 회원 본인 폴더(<회원 id>/...)에만 올리고 지울 수 있음
--    만든 지 30일 지난 글·이미지·글감은 매일 자동 정리됩니다(/api/cron/cleanup-images, vercel.json).
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public) values ('post-images', 'post-images', true) on conflict (id) do nothing;
drop policy if exists post_images_select_public on storage.objects;
create policy post_images_select_public on storage.objects for select to public using (bucket_id = 'post-images');
drop policy if exists post_images_insert_own on storage.objects;
create policy post_images_insert_own on storage.objects for insert to authenticated with check (bucket_id = 'post-images' and auth.uid()::text = (storage.foldername(name))[1]);
drop policy if exists post_images_update_own on storage.objects;
create policy post_images_update_own on storage.objects for update to authenticated using (bucket_id = 'post-images' and auth.uid()::text = (storage.foldername(name))[1]);
drop policy if exists post_images_delete_own on storage.objects;
create policy post_images_delete_own on storage.objects for delete to authenticated using (bucket_id = 'post-images' and auth.uid()::text = (storage.foldername(name))[1]);

-- ---------------------------------------------------------------------
-- 9. NewsBlur 계정(선택 — RSS 글감 수집에서 NewsBlur를 쓸 때만)
--    설치마법사가 이 표로 DB 만들기 성공을 확인하므로 항상 파일 맨 끝에 둡니다.
-- ---------------------------------------------------------------------
create table if not exists public.newsblur_accounts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  username text not null,
  password text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.newsblur_accounts enable row level security;
drop policy if exists newsblur_accounts_owner on public.newsblur_accounts;
create policy newsblur_accounts_owner on public.newsblur_accounts for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- 권한 보강(Supabase 새 프로젝트 화면의 「Automatically expose new tables」를 꺼도 동작하게, 2026-10-30)
grant select, insert, update, delete on public.user_api_keys, public.newsblur_accounts to authenticated;
