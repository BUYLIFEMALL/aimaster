import { loadPlatformEnv } from './platform-env.mjs';
// Public live-page verification in visible Chrome. Does not authenticate or call AI.
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { createClient } from '@supabase/supabase-js';
import assert from 'node:assert/strict';
const expected = JSON.parse(await fs.readFile('docs/catalog-content-20261016.json', 'utf8'));
const artwork = JSON.parse(await fs.readFile('docs/catalog-thumbnail-release-20261016.json', 'utf8'));
const env = await loadPlatformEnv();
const client = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const { data: row, error } = await client.from('programs').select('id,slug,name,short_desc,description,detail_sections,thumbnail_url,app_url,is_active,version,extension_version,extension_download_url').eq('slug', 'blog-content-maker').single();
if (error) throw error;
assert.equal(row.is_active, true);
assert.equal(row.name, 'AI 블로그 콘텐츠 제작 자동화');
for (const key of ['short_desc', 'description', 'detail_sections']) assert.deepEqual(row[key], expected[key]);
assert.equal(row.thumbnail_url, artwork.thumbnail_url);
assert.equal(row.app_url, 'https://blog-content-maker.buylife.xyz');
const appVersion = /APP_VERSION\s*=\s*"(v\d+\.\d+)"/.exec(await fs.readFile('src/lib/version.ts', 'utf8'))?.[1];
assert.equal(row.version, appVersion); assert.equal(row.extension_version, appVersion);
const visible = row.description.replace(/<[^>]+>/g, '');
assert.ok([...visible].length >= 400 && [...visible].length <= 500);
assert.equal((row.description.match(/<p>/g) || []).length, 6);
assert.equal((row.description.match(/<strong>/g) || []).length, 1);
assert.ok(!/<p>\s*(<br\s*\/?>)?\s*<\/p>/i.test(row.description));
const { data: plans, error: plansError } = await client.from('pricing_plans').select('name,billing_type,price,is_active').eq('program_id', row.id).order('sort_order');
if (plansError) throw plansError;
assert.equal(plans.length, 3); assert.ok(plans.every(p => p.is_active));
const output = path.resolve('test-artifacts'); await fs.mkdir(output, { recursive: true });
const context = await chromium.launchPersistentContext(path.resolve('.local/catalog-browser'), { channel: 'chrome', headless: false, viewport: { width: 1360, height: 940 } });
const page = context.pages()[0] || await context.newPage();
const checks = [];
function check(name, value) { assert.ok(value, name); checks.push({ name, passed: true }); console.log('PASS', name); }
try {
  const url = 'https://www.buylife.xyz/programs/blog-content-maker';
  const response = await page.goto(url, { waitUntil: 'networkidle' });
  check('live detail HTTP 200', response.status() === 200);
  await page.getByRole('heading', { name: row.name, exact: true }).first().waitFor();
  const body = await page.locator('body').innerText();
  for (const f of expected.detail_sections.features) check('feature ' + f.title, body.includes(f.title) && body.includes(f.desc));
  for (const s of expected.detail_sections.steps) check('step ' + s.title, body.includes(s.title) && body.includes(s.desc));
  check('description current and complete', body.includes('주제나 기존 원고로 글·이미지를 만들고') && body.includes('점검은 네이버 공식 점수가 아니며 최종 발행은 직접 합니다.'));
  const loaded = await page.locator('img').evaluateAll(images => images.filter(img => (img.currentSrc || img.src).includes('blog-content-maker-thumbnail')).map(img => ({ complete: img.complete, width: img.naturalWidth, height: img.naturalHeight })));
  check('dedicated thumbnail loaded', loaded.length > 0 && loaded.every(img => img.complete && img.width > 0));
  check('anonymous visitor retains subscription gate', await page.locator('a[href="https://blog-content-maker.buylife.xyz"]').count() === 0 && body.includes('구독'));
  await page.screenshot({ path: path.join(output, 'catalog-detail-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 400, height: 860 });
  await page.screenshot({ path: path.join(output, 'catalog-detail-mobile.png'), fullPage: true });
  check('400px detail no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.setViewportSize({ width: 1360, height: 940 });
  const catalog = await page.goto('https://www.buylife.xyz/programs?q=' + encodeURIComponent('블로그') + '&sort=newest', { waitUntil: 'networkidle' });
  check('catalog HTTP 200', catalog.status() === 200);
  const card = page.locator('a[href="/programs/blog-content-maker"]').first();
  await card.waitFor();
  check('catalog contains current summary', (await page.locator('body').innerText()).includes(expected.short_desc));
  const cardImage = page.getByAltText(row.name, { exact: true }).first();
  await cardImage.waitFor();
  check('catalog thumbnail loads', await cardImage.evaluate(img => img.complete && img.naturalWidth > 0 && (img.currentSrc || img.src).includes('blog-content-maker-thumbnail')));
  await page.screenshot({ path: path.join(output, 'catalog-card-comparison.png'), fullPage: true });
  await Promise.all([page.waitForURL('**/programs/blog-content-maker'), card.click()]);
  await page.getByRole('heading', { name: row.name, exact: true }).first().waitFor();
  check('catalog card opens correct detail', new URL(page.url()).pathname === '/programs/blog-content-maker');
  await fs.writeFile(path.join(output, 'catalog-result.json'), JSON.stringify({ url, version: row.version, visibleChars: [...visible].length, shortChars: [...row.short_desc].length, paragraphs: 6, features: 4, steps: 4, plans, thumbnail: artwork, checks, desktop: { width: 1360, height: 940 }, mobile: { width: 400, height: 860 } }, null, 2));
  console.log('CATALOG VERIFIED', checks.length);
} finally { await context.close(); }
