// Reproduce the v1.04 regression with metadata bytes only; contains no music recording.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { parseId3 } from "../src/lib/player/id3.ts";
const baseline = "ad0d91a2";
await mkdir("test-artifacts", {recursive:true});
const originalFile = path.resolve("test-artifacts/id3-before.ts");
await writeFile(originalFile, execFileSync("git", ["show", `${baseline}:music-player/src/lib/player/id3.ts`]));
const original = await import(pathToFileURL(originalFile).href);
const text = Buffer.from([0,179,187,32,180,171,191,161,32,186,184,191,169]);
const frame = Buffer.alloc(10); frame.write("TIT2"); frame.writeUInt32BE(text.length,4);
const size=frame.length+text.length;
const file=Uint8Array.from([73,68,51,3,0,0,(size>>21)&127,(size>>14)&127,(size>>7)&127,size&127,...frame,...text]).buffer;
const before=original.parseId3(file).title, after=parseId3(file).title;
assert.notEqual(before,"내 눈에 보여");assert.equal(after,"내 눈에 보여");
const proof={baseline,fixture:"synthetic ID3v2.3 metadata, encoding flag 0 / Korean bytes",before,after,original_bug_reproduced:true,fixed:true};
await mkdir("docs/evidence",{recursive:true});
await writeFile("docs/evidence/id3-regression.json",JSON.stringify(proof,null,2)+"\n");
console.log(JSON.stringify(proof));
