// 기본 서식은 공정위 전자상거래 표준약관·개인정보 처리방침 작성 지침의 일반 목차를 바탕으로 한 초안이다(법률 검토 아님).
// 운영사가 사업장에 맞게 고쳐 쓴다(화면 안내). DB 0097 mall_builder_store_policies.

export type PolicyKind = "terms" | "privacy";
export const POLICY_KINDS: PolicyKind[] = ["terms", "privacy"];
export const POLICY_LABEL: Record<PolicyKind, string> = { terms: "이용약관", privacy: "개인정보 처리방침" };
export const POLICY_PATH: Record<PolicyKind, string> = { terms: "/terms", privacy: "/privacy" };
export const POLICY_MAX = 60000;

export function isPolicyKind(v: unknown): v is PolicyKind {
  return v === "terms" || v === "privacy";
}

export type PolicyInfo = { storeName: string; company: string; ceo: string; address: string; phone: string; email: string; officer: string };

const or = (v: string, fallback: string) => (v && v.trim() ? v.trim() : fallback);

