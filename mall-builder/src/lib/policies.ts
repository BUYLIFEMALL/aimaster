/** 저장 전 정리 — 제어문자 제거, 줄바꿈 통일, 앞뒤 공백 */
export function cleanPolicyBody(v: unknown): { ok: true; value: string } | { ok: false; error: string } {
  const s = String(v ?? "").replace(/\r\n?/g, "\n").replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "").trim();
  if (s.length > POLICY_MAX) return { ok: false, error: `${POLICY_MAX.toLocaleString("ko-KR")}자 이내로 입력해 주세요(지금 ${s.length.toLocaleString("ko-KR")}자).` };
  return { ok: true, value: s };
}
