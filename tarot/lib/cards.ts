function buildMinorSuit(suit: Suit, suitKo: string, data: [string, string][]): TarotCard[] {
  return MINOR_NUMBERS.map((spec, idx) => {
    const [upright, reversed] = data[idx];
    const nameKo = `${suitKo} ${spec.cardKo}`;
    const nameEn = `${spec.cardEn} of ${SUIT_LABELS_EN[suit]}`;
    return {
      id: `minor-${suit}-${String(spec.number).padStart(2, "0")}`,
      arcana: "minor" as const,
      suit,
      number: spec.number,
      nameKo,
      nameEn,
      keywords: [suitKo, spec.cardKo],
      upright,
      reversed,
    };
  });
}

const MINOR_ARCANA: TarotCard[] = [
  ...buildMinorSuit("wands", SUIT_LABELS.wands, WANDS),
  ...buildMinorSuit("cups", SUIT_LABELS.cups, CUPS),
  ...buildMinorSuit("swords", SUIT_LABELS.swords, SWORDS),
  ...buildMinorSuit("pentacles", SUIT_LABELS.pentacles, PENTACLES),
];

export const TAROT_DECK: TarotCard[] = [...MAJOR_ARCANA, ...MINOR_ARCANA];

export const CARD_MAP: Record<string, TarotCard> = Object.fromEntries(
  TAROT_DECK.map((c) => [c.id, c]),
);

export function getCard(id: string): TarotCard | undefined {
  return CARD_MAP[id];
}
