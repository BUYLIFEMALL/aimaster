import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const before = JSON.parse(fs.readFileSync(path.join(root, 'docs/evidence/prompts-before-20261020.json'), 'utf8'));
const after = JSON.parse(fs.readFileSync(path.join(root, 'lib/prompts/stylePresetPrompts.json'), 'utf8'));
const rollback = process.argv.includes('--rollback');
const edits = before.map(row => {
  const replacement = after.find(item => item.style_id === row.style_id && item.label === row.label);
  if (!replacement || replacement.display_order !== row.display_order) throw new Error('Catalog identity mismatch: ' + row.label);
  return { ...row, expected_prompt: rollback ? replacement.prompt : row.prompt, replacement_prompt: rollback ? row.prompt : replacement.prompt };
});
if (before.length !== 160 || after.length !== 160 || new Set(edits.map(row => row.id)).size !== 160) {
  throw new Error('Expected exactly 160 distinct existing templates');
}
const payload = JSON.stringify(edits.map(({ id, style_id, label, display_order, created_at, expected_prompt, replacement_prompt }) => ({
  id, style_id, label, display_order, created_at, expected_prompt, replacement_prompt,
})));
if (payload.includes('$catalog_payload$')) throw new Error('Unexpected SQL delimiter in editorial content');
const sql = `-- Editorial template data only. No schema, account, API key or member content changes.
-- Generated by scripts/build-style-prompt-release.mjs${rollback ? ' --rollback' : ''}.
-- Preflight rejects any intervening administrator/CLI edit. The DO statement is atomic.
DO $release$
DECLARE
  payload jsonb := $catalog_payload$${payload}$catalog_payload$::jsonb;
  matched_count integer;
  changed_count integer;
BEGIN
  SET LOCAL lock_timeout = '5s';
  SET LOCAL statement_timeout = '30s';
  LOCK TABLE public.style_preset_prompts IN SHARE ROW EXCLUSIVE MODE;
  IF (SELECT count(*) FROM public.style_preset_prompts) <> 160 THEN
    RAISE EXCEPTION 'Template count changed; review current catalog before applying';
  END IF;
  SELECT count(*) INTO matched_count
  FROM public.style_preset_prompts p
  JOIN jsonb_to_recordset(payload) AS e(id uuid, style_id text, label text, display_order integer, created_at timestamptz, expected_prompt text)
    ON p.id = e.id
  WHERE p.style_id = e.style_id AND p.label = e.label
    AND p.display_order = e.display_order AND p.created_at = e.created_at
    AND p.prompt = e.expected_prompt;
  IF matched_count <> 160 THEN
    RAISE EXCEPTION 'Template content or identity changed (%/160 match); refusing to overwrite', matched_count;
  END IF;
  UPDATE public.style_preset_prompts p
  SET prompt = e.replacement_prompt
  FROM jsonb_to_recordset(payload) AS e(id uuid, replacement_prompt text)
  WHERE p.id = e.id;
  GET DIAGNOSTICS changed_count = ROW_COUNT;
  IF changed_count <> 160 THEN
    RAISE EXCEPTION 'Unexpected updated count: %', changed_count;
  END IF;
END
$release$;
SELECT style_id, count(*) AS count, min(length(prompt)) AS shortest, max(length(prompt)) AS longest
FROM public.style_preset_prompts GROUP BY style_id ORDER BY style_id;
`;
const output = path.join(root, 'docs/releases', rollback ? '20261020_prompts_v120_rollback.sql' : '20261020_prompts_v120.sql');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, sql);
console.log(JSON.stringify({ output: path.relative(root, output), templates: edits.length, rollback, executed: false }));
