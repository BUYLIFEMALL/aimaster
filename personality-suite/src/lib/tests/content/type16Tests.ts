import type { Axis, Pole, Type16Question, Type16Test } from "../types";

// 상황별 16유형 검사 10종. 각 검사는 20문항(축마다 5문항, 앞 극·뒤 극 문항을 섞어 한쪽으로 쏠린 응답을 줄인다).
// 문항·상황 해석은 모두 이 프로그램에서 새로 쓴 문장이다. 공식 MBTI(The Myers-Briggs Company 상표) 문항·리포트와 무관하다.

type Item = [text: string, pole: Pole];

function build(
  id: string, title: string, tagline: string, description: string, lensTitle: string, minutes: number,
  ei: Item[], sn: Item[], tf: Item[], jp: Item[], lens: Record<Pole, string>,
): Type16Test {
  const mk = (axis: Axis, items: Item[]): Type16Question[] => items.map(([text, pole]) => ({ text, axis, pole }));
  return {
    id, group: "type16", kind: "type16", title, tagline, description, lensTitle, minutes, lens,
    questions: [...mk("EI", ei), ...mk("SN", sn), ...mk("TF", tf), ...mk("JP", jp)],
  };
}

